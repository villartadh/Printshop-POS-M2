"""Real SQLite versioned schedule and recurring expense link invariants."""
import drawer_journal_schema_test as prior
from drawer_journal_schema_test import *
import datetime
recurring=statements("RecurringJournal.java")
assert len(recurring)==12
start=prior.checks
with sqlite3.connect(":memory:") as db:
    db.execute("PRAGMA foreign_keys=ON")
    db.execute("PRAGMA recursive_triggers=OFF")
    for _,sqls in stages:
        for sql in sqls: db.execute(sql)
    db.execute("INSERT INTO catalog VALUES('service','SERVICE','Synthetic service','page',100,1,0)")
    account(db,"owner","OWNER");account(db,"staff","CASHIER")
    for sql in drawer+statements("RefundJournal.java"): db.execute(sql)
    shift(db,"open","owner",1000);shift(db,"staff-open","staff",500)
    historic=snapshot(db,["cashier_shifts","cashier_drawer_effects","checkout_requests","stock_movements"])
    for sql in recurring: db.execute(sql)
    check(snapshot(db,list(historic))==historic,"v13 migration preserves financial data")
    check(db.execute("SELECT COUNT(*) FROM cashier_recurring_versions").fetchone()==(0,),"no invented definitions")
    def ts(d):
        return int(datetime.datetime.fromisoformat(d+"T12:00:00+08:00").timestamp()*1000)
    def version(sid="rent",rev=1,first="2024-01-31",amount=100,active=1,actor="owner",cadence="MONTHLY"):
        return (sid,rev,"Synthetic rent","Synthetic rent",amount,cadence,first,active,actor,1,ts("2024-03-31"))
    version_sql="INSERT INTO cashier_recurring_versions VALUES("+",".join("?"*11)+")"
    def save(**kw): db.execute(version_sql,version(**kw))
    def due(sid="rent"): return db.execute("SELECT revision,next_index,next_due,active FROM cashier_recurring_due WHERE id=?",(sid,)).fetchone()
    reject(db,version_sql,version(actor="staff"))
    reject(db,version_sql,version(rev=2))
    reject(db,version_sql,version(active=0))
    reject(db,version_sql,version(first="2026-02-29"))
    reject(db,version_sql,version(amount=0))
    save();check(due()==(1,0,"2024-01-31",1),"initial monthly due")
    check(cash(db,"open")==1000 and effects(db,"open")==[],"definition no cash effect")
    reject(db,"UPDATE cashier_recurring_versions SET amount=1 WHERE id='rent'")
    reject(db,"DELETE FROM cashier_recurring_versions WHERE id='rent'")
    reject(db,version_sql.replace("INSERT","INSERT OR REPLACE"),version())
    def occurrence(req,index,date,amount=100,before=1000,at="2024-03-31",actor="owner",sid="open",rev=1):
        with db:
            stage(db,req,sid=sid,actor=actor,kind="EXPENSE",amount=amount,category="Synthetic rent",before=before,at=ts(at))
            db.execute("INSERT INTO cashier_recurring_occurrences VALUES(?,?,?,?,?)",(req,"rent",rev,index,date))
    def bad_occ(req,*args,**kw):
        db.commit()
        try: occurrence(req,*args,**kw)
        except sqlite3.IntegrityError: check(state(db,req) is None,"invalid occurrence atomic rollback")
        else: raise AssertionError("invalid occurrence accepted")
    bad_occ("future",0,"2024-01-31",at="2024-01-30")
    bad_occ("skipped",1,"2024-02-29")
    bad_occ("wrongdate",0,"2024-02-01")
    bad_occ("amount",0,"2024-01-31",amount=101)
    bad_occ("cashier",0,"2024-01-31",before=500,actor="staff",sid="staff-open")
    occurrence("pending",0,"2024-01-31")
    check(cash(db,"open")==1000 and due()==(1,0,"2024-01-31",1),"pending does not advance or debit")
    reject(db,version_sql,version(rev=2,first="2024-04-30"))
    reject(db,"DELETE FROM cashier_recurring_occurrences WHERE drawer_id='pending'")
    reject(db,"UPDATE cashier_recurring_occurrences SET due_date='2024-02-01' WHERE drawer_id='pending'")
    reject(db,"INSERT OR REPLACE INTO cashier_recurring_occurrences VALUES('pending','rent',1,0,'2024-01-31')")
    resolve(db,"pending",at=ts("2024-03-31"),apply=False)
    check(due()==(1,0,"2024-01-31",1) and cash(db,"open")==1000,"cancellation no effect or skipped due")
    occurrence("jan",0,"2024-01-31")
    db.execute("CREATE TRIGGER recurring_fault BEFORE INSERT ON cashier_drawer_effects BEGIN SELECT RAISE(ABORT,'fault'); END")
    reject(db,"UPDATE cashier_drawer_requests SET state='APPLIED',resolved_revision=1,resolved_ms=? WHERE id='jan'",(ts("2024-03-31"),))
    check(due()==(1,0,"2024-01-31",1) and state(db,"jan")[0]=="PENDING","fault rollback")
    db.execute("DROP TRIGGER recurring_fault")
    resolve(db,"jan",at=ts("2024-03-31"))
    check(due()==(1,1,"2024-02-29",1) and cash(db,"open")==900,"leap next and exact debit")
    bad_occ("duplicate",0,"2024-01-31",before=900)
    occurrence("feb",1,"2024-02-29",before=900);resolve(db,"feb",at=ts("2024-03-31"))
    check(due()==(1,2,"2024-03-31",1) and cash(db,"open")==800,"monthly no clamp drift")
    db.commit()
    reject(db,version_sql,version(rev=2,first="2024-02-29"))
    save(rev=2,first="2024-04-30",amount=125)
    check(due()==(2,0,"2024-04-30",1),"version effective date")
    bad_occ("old-revision",2,"2024-03-31",before=800)
    save(rev=3,first="2024-04-30",amount=125,active=0)
    check(due()==(3,0,"2024-04-30",0),"archive append")
    bad_occ("archived",0,"2024-04-30",amount=125,before=800,rev=3,at="2024-05-01")
    check(db.execute("SELECT COUNT(*) FROM cashier_recurring_versions").fetchone()==(3,),"immutable version history")
    check(db.execute("SELECT COUNT(*) FROM cashier_drawer_effects").fetchone()==(2,),"one financial effect per applied recurring occurrence")
    check(db.execute("SELECT COUNT(*) FROM cashier_recurring_occurrences").fetchone()==(3,),"cancelled audit retained")
    report_source=(root/"ReportJournal.java").read_text()
    events=re.search(r'String EVENTS="([^"]+)"',report_source).group(1)
    rows=db.execute(events,(0,2**63-1,0,2**63-1)).fetchall()
    check(sorted((r[0],r[1],r[5]) for r in rows)==[("EXPENSE",100,"feb"),("EXPENSE",100,"jan")],"report counts recurring expenses once and excludes cancelled")
    history_source=(root/"RecurringJournal.java").read_text()
    history=re.search(r'db.rawQuery\("(SELECT o.drawer_id FROM cashier_recurring_occurrences[^"]+)"',history_source).group(1)
    check(db.execute(history,("owner","2","0")).fetchall()==[("pending",),("jan",)],"history bounded")
    check(db.execute(history,("staff","9","0")).fetchall()==[],"history scoped")

    save(sid="weekly",first="2024-12-30",cadence="WEEKLY")
    save(sid="daily",first="2024-12-31",cadence="DAILY")
    check(due("weekly")[2]=="2024-12-30" and due("daily")[2]=="2024-12-31","weekly and daily")
    check(not db.execute("PRAGMA foreign_key_check").fetchall(),"foreign keys")
print(f"Recurring journal actual SQLite: {prior.checks-start} checks PASS")
