    reject(db,insert,quote("q1"))
    reject(db,"UPDATE saved_quotations SET total_centavos=1 WHERE id='q1'")
    reject(db,"DELETE FROM saved_quotations WHERE id='q1'")
    cancel="INSERT INTO saved_quotation_cancellations VALUES(?,?,?,?,?)"
