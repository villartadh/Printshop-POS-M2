"""SQLite v15 customer attribution, historical snapshots and cash isolation."""
import drawer_journal_schema_test as prior
from drawer_journal_schema_test import *
start=prior.checks
with sqlite3.connect(":memory:") as db:
    db.execute("PRAGMA foreign_keys=ON")
    db.execute("PRAGMA recursive_triggers=OFF")
    for _,sqls in stages:
        for sql in sqls: db.execute(sql)
    account(db,"owner","OWNER");account(db,"staff","CASHIER")
    db.execute("INSERT INTO catalog VALUES('service','SERVICE','Synthetic service','page',100,1,0)")
    shift(db,"old","owner",1000)
    sale_stage(db,"old-sale","old","owner",100);sale_apply(db,"old-sale",100)
    close(db,"old",1100,1100)
    for sql in drawer+statements("RefundJournal.java")+statements("RecurringJournal.java")+statements("CustomerJournal.java"): db.execute(sql)
    db.execute("INSERT INTO cashier_customer_versions VALUES('cust',1,'Original name','Private synthetic contact',1,'owner',1,2)")
    db.execute("INSERT INTO cashier_customer_versions VALUES('archived',1,'Archived name','',1,'owner',1,2)")
    db.execute("INSERT INTO cashier_customer_versions VALUES('archived',2,'Archived name','',0,'owner',1,3)")
    names=["cashier_customer_versions","checkout_requests","checkout_sales","checkout_cash","cashier_drawer_effects","cashier_shifts"]
    before=snapshot(db,names)
    for sql in statements("CustomerLinkJournal.java"): db.execute(sql)
    check(snapshot(db,names)==before,"migration preserves existing identities and sales")
    check(db.execute("SELECT COUNT(*) FROM cashier_checkout_customers").fetchone()==(0,),"no invented assignment")
    link="INSERT INTO cashier_checkout_customers VALUES(?,?,?,?,?)"
    reject(db,link,("old-sale","cust",1,"owner",1))
    shift(db,"open","staff",1000)
    sale_stage(db,"named","open","staff",100)
    reject(db,link,("named","cust",1,"owner",1))
    reject(db,link,("named","cust",1,"staff",2))
    reject(db,link,("named","archived",2,"staff",1))
    reject(db,link,("named","cust",9,"staff",1))
    reject(db,link,("named",None,1,"staff",1))
    db.execute(link,("named","cust",1,"staff",1))
    check(cash(db,"open")==1000,"attribution alone no cash")
    reject(db,link.replace("INSERT","INSERT OR REPLACE"),("named",None,None,"staff",1))
    reject(db,"UPDATE cashier_checkout_customers SET customer_id=NULL,customer_revision=NULL WHERE request_id='named'")
    reject(db,"DELETE FROM cashier_checkout_customers WHERE request_id='named'")
    db.execute("INSERT INTO cashier_customer_versions VALUES('cust',2,'Renamed','Another private contact',0,'owner',1,4)")
    src=(root/"CustomerLinkJournal.java").read_text()
    read=re.search(r'db.rawQuery\("(SELECT v.id,v.name,v.revision FROM cashier_checkout_customers[^"]+)"',src).group(1)
    check(db.execute(read,("named",)).fetchone()==("cust","Original name",1),"immutable staged identity after archive")
    sale_apply(db,"named",100)
    check(cash(db,"open")==1100 and len(effects(db,"open"))==1,"named full cash checkout exactly once")
    check(db.execute(read,("named",)).fetchone()==("cust","Original name",1),"recorded receipt preserves snapshot")
    sale_stage(db,"walkin","open","staff",100)
    reject(db,link,("walkin","cust",1,"staff",1))
    db.execute(link,("walkin",None,None,"staff",1))
    cancel_sale(db,"walkin")
    check(db.execute(read,("walkin",)).fetchone() is None and cash(db,"open")==1100,"cancelled walk-in no cash")
    check(db.execute(read,("old-sale",)).fetchone() is None,"historical attribution absent")
    db.commit()
    try:
        with db:
            sale_stage(db,"fault","open","staff",100)
            db.execute(link,("fault","cust",2,"staff",1))
    except sqlite3.IntegrityError: pass
    else: raise AssertionError("archived assignment accepted")
    check(db.execute("SELECT COUNT(*) FROM checkout_requests WHERE request_id='fault'").fetchone()==(0,),"invalid link rolls back pending checkout")
    db.execute("INSERT INTO cashier_customer_versions VALUES('cust',3,'Restored name','Private',1,'owner',1,5)")
    query=re.search(r'db.rawQuery\("(SELECT id,name,revision FROM cashier_customer_current[^"]+)"',src).group(1)
    check(db.execute(query,("RESTORED",9,0)).fetchall()==[("cust","Restored name",3)],"active name projection excludes contact")
    check(db.execute(query,("",9,0)).fetchall()==[("cust","Restored name",3)],"archived excluded")
    check(not db.execute("PRAGMA foreign_key_check").fetchall(),"foreign keys")
print(f"Customer checkout actual SQLite: {prior.checks-start} checks PASS")
